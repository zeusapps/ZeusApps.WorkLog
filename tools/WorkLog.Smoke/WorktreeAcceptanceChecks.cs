using System.Text.Json;
using System.Text.Json.Nodes;
using ModelContextProtocol.Client;
using ModelContextProtocol.Protocol;
using Tomlyn;
using Tomlyn.Model;
using WorkLog.Configuration;
using WorkLog.Repositories;

namespace WorkLog.Smoke;

internal sealed class WorktreeAcceptanceChecks(SmokeWorkspace workspace, SmokeProcessRunner processes)
{
    private readonly string root = Path.Combine(workspace.Root, "worktree-startup");
    private readonly List<Probe> probes = [];
    private readonly HashSet<string> observationIds = [];
    private readonly Dictionary<string, string> versions = [];
    private readonly List<string> setupLogs = [];
    private string Main => Path.Combine(root, "main checkout");
    private string Worktree => Path.Combine(root, "external worktree");
    private string Home => Path.Combine(root, "home");
    private string Data => Path.Combine(root, "data");
    private string CodexHome => Path.Combine(Home, ".codex");
    private string? identity;
    private bool freshProbeBeforeInit;
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web) { WriteIndented = true };
    private Dictionary<string, string> EnvironmentForFixture => new()
    {
        ["CODEX_HOME"] = CodexHome,
        ["CLAUDE_CONFIG_DIR"] = Home,
        ["WORKLOG_DATA_DIR"] = Data,
        ["HOME"] = Home,
        ["USERPROFILE"] = Home,
        ["LOCALAPPDATA"] = Path.Combine(Home, "localappdata"),
        ["APPDATA"] = Path.Combine(Home, "appdata")
    };

    public async Task RunAsync()
    {
        Directory.CreateDirectory(Main);
        Directory.CreateDirectory(CodexHome);
        string? failure = null;
        try
        {
            // Nothing generated by WorkLog is committed or copied to the sibling worktree.
            await GitAsync(Main, "init");
            await GitAsync(Main, "-c", "user.name=Smoke", "-c", "user.email=smoke@example.invalid",
                "-c", "commit.gpgsign=false", "commit", "--allow-empty", "-m", "worktree fixture");
            var settings = new LocalSettings(Data);
            settings.Configuration.Updates.Enabled = false;
            settings.Save();
            foreach (var client in new[] { "git", "codex", "claude", workspace.Executable })
                versions[Path.GetFileName(client)] = (await RunAsync(client, ["--version"], Main)).Output.Trim();
            await InitAsync(Main, "both", "--ticket-provider", "jira", "--ticket-scope", "worktree.example.invalid");
            identity = new RepositoryRegistry(new LocalSettings(Data)).Get(Main).Identity;
            await GitAsync(Main, "worktree", "add", "-b", "worktree-smoke", Worktree);
            Require(SamePath(GitRepository.GetCommonDirectory(Main), GitRepository.GetCommonDirectory(Worktree)),
                "The fixture checkouts do not share a Git common directory.");

            // Persist trust only in the disposable home, for each actual launch directory.
            File.WriteAllText(Path.Combine(CodexHome, "config.toml"), string.Join('\n', new[] { Main, Worktree }
                .Select(path => "[projects." + JsonSerializer.Serialize(path) + "]\ntrust_level = 'trusted'\n")));
            foreach (var client in new[] { "claude", "codex" })
                await ProbeAsync(client, "main-initialized", Main, required: true);
            Require(probes.All(probe => probe.Failure is null), "Main-checkout baseline failed; worktree inheritance cannot be interpreted.");

            AssertFreshWorktree();
            freshProbeBeforeInit = true;
            foreach (var client in new[] { "claude", "codex" })
                await ProbeAsync(client, "worktree-before-init", Worktree, required: false);
            AssertFreshWorktree();
            foreach (var client in new[] { "claude", "codex" })
            {
                await InitAsync(Worktree, client);
                await ProbeAsync(client, "worktree-after-init", Worktree, required: true);
                await ProbeAsync(client, "main-after-worktree-init", Main, required: true);
            }
            Require(probes.Count == 8 && probes.All(probe => probe.Failure is null),
                "Worktree acceptance failed. See the stage results and logs.");
        }
        catch (Exception error) when (error is not OutOfMemoryException)
        {
            failure = error.Message;
            throw;
        }
        finally
        {
            var summary = JsonSerializer.Serialize(new
            {
                outcome = failure is null ? "passed" : "failed",
                failure,
                windows = System.Environment.OSVersion.ToString(),
                versions,
                main = Main,
                worktree = Worktree,
                gitCommonDirectory = Directory.Exists(Path.Combine(Main, ".git")) ? Path.Combine(Main, ".git") : null,
                clientHome = Home,
                dataDirectory = Data,
                repositoryIdentity = identity,
                freshProbeBeforeInit,
                setupLogs,
                coverage = "Manually created external worktree, terminal clients, isolated profiles, no authenticated prompts",
                untested = new[] { "Desktop", "Claude-managed --worktree sessions", "authenticated agent tool use" },
                probes
            }, JsonOptions);
            Require(System.Text.Encoding.UTF8.GetByteCount(summary) <= 64 * 1024, "Worktree summary exceeds its 64 KiB bound.");
            File.WriteAllText(Path.Combine(root, "evidence.json"), summary);
            Console.WriteLine("WORKTREES " + (failure is null ? "PASSED" : "FAILED") + ". Evidence: " + Path.Combine(root, "evidence.json"));
        }
    }

    private async Task ProbeAsync(string client, string stage, string checkout, bool required)
    {
        var probe = new Probe(client, stage, checkout);
        probes.Add(probe);
        var phase = "configuration-discovery";
        try
        {
            var result = await processes.RunDetailedAsync(client, client == "codex"
                ? ["-c", SmokeWorkspace.TrustOverrideFor(checkout), "mcp", "list", "--json"]
                : ["mcp", "get", "worklog"], EnvironmentForFixture, checkout);
            probe.ClientExitCode = result.ExitCode;
            probe.Logs.Add(Relative(result.LogPath));
            Registration? registration;
            if (client == "codex")
            {
                Require(result.ExitCode == 0, "Codex discovery command failed; see its log.");
                using var json = JsonDocument.Parse(result.Output);
                var servers = json.RootElement.EnumerateArray().Where(server => server.GetProperty("name").GetString() == "worklog").ToArray();
                Require(servers.Length <= 1, "Codex returned multiple WorkLog definitions.");
                if (servers.Length == 0)
                    registration = null;
                else
                {
                    Require(servers[0].GetProperty("enabled").GetBoolean(), "Codex discovered a disabled WorkLog registration.");
                    var transport = servers[0].GetProperty("transport");
                    Require(transport.GetProperty("type").GetString() == "stdio", "Expected a stdio registration.");
                    registration = new(transport.GetProperty("command").GetString()!,
                        transport.GetProperty("args").EnumerateArray().Select(argument => argument.GetString()!).ToArray());
                    Require(!transport.TryGetProperty("cwd", out var cwd) || cwd.ValueKind == JsonValueKind.Null,
                        "Fixture registration unexpectedly overrides the client's working directory.");
                }
                probe.NativeHealth = "unavailable: list reports configuration, not connection health";
            }
            else
            {
                var text = result.Output + "\n" + result.Error;
                if (result.ExitCode != 0 && text.Contains("No MCP server found", StringComparison.OrdinalIgnoreCase))
                    registration = null;
                else
                {
                    Require(result.ExitCode == 0, "Claude discovery/health command failed; see its log.");
                    registration = ReadClaudeRegistration(result.Output);
                    probe.NativeHealth = result.Output.Contains("✔ Connected", StringComparison.Ordinal)
                        ? "connected" : "failed";
                }
            }
            probe.Discovery = registration is null ? "absent" : "found";
            if (registration is null)
            {
                Require(!required, "WorkLog was not discovered after explicit setup.");
                Console.WriteLine($"  {client} {stage}: discovery=absent (pre-init finding); connection not attempted.");
                return;
            }
            probe.Command = registration.Command;
            probe.Arguments = registration.Arguments;
            probe.RepositoryArgument = Argument(registration, "--repository");
            probe.DataDirectoryArgument = Argument(registration, "--data-dir");
            Require(SamePath(registration.Command, workspace.Executable), "Client discovered an unexpected executable.");
            Require(probe.RepositoryArgument is { } repository && (SamePath(repository, Main) || SamePath(repository, Worktree)),
                "Client discovered a repository outside the disposable fixture.");
            Require(probe.DataDirectoryArgument is { } data && SamePath(data, Data), "Client discovered an unexpected data directory.");
            // A client may prefer the inherited main definition even after worktree init.
            // Verify the written definition separately; judge the effective one by context.
            Require(!SamePath(checkout, Main) || SamePath(probe.RepositoryArgument!, Main), "Main-checkout registration was displaced.");

            phase = "process-launch";
            await CheckProtocolAsync(probe, registration, () => phase = "mcp-initialization",
                () => phase = "mcp-tool-discovery", () => phase = "repository-context");
            phase = "client-health";
            Require(client != "claude" || probe.NativeHealth == "connected", "Claude discovered the server but its native connection check failed.");
        }
        catch (Exception error) when (error is not OutOfMemoryException)
        {
            probe.Failure = phase + ": " + error.Message[..Math.Min(error.Message.Length, 1000)];
            if (phase == "configuration-discovery" && probe.Discovery == "not-run")
                probe.Discovery = "failed";
            if (phase == "process-launch")
                probe.ProcessLaunch = "failed";
            if (phase.StartsWith("mcp-", StringComparison.Ordinal))
                probe.Protocol = "failed";
            if (phase == "repository-context")
                probe.Context = "failed";
        }
        Console.WriteLine($"  {client} {stage}: discovery={probe.Discovery}, native={probe.NativeHealth}, launch={probe.ProcessLaunch}, protocol={probe.Protocol}, context={probe.Context}" +
            (probe.Failure is null ? "" : ", FAILED: " + probe.Failure));
    }

    private async Task CheckProtocolAsync(Probe probe, Registration registration, Action launched, Action initialized, Action toolsListed)
    {
        var log = Path.Combine(root, probe.Client + "-" + probe.Stage + "-protocol.log");
        probe.Logs.Add(Relative(log));
        var logGate = new object();
        void Log(string text)
        {
            lock (logGate)
                File.AppendAllText(log, text + "\n");
        }
        Log(JsonSerializer.Serialize(new
        {
            registration.Command,
            registration.Arguments,
            probe.Checkout,
            protocolCheck = "direct SDK, separate from native health"
        }));
        var environment = StdioClientTransportOptions.GetDefaultEnvironmentVariables();
        foreach (var (key, value) in EnvironmentForFixture)
            environment[key] = value;
        using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(40));
        var transport = new StdioClientTransport(new()
        {
            Name = "worktree-" + probe.Client + "-" + probe.Stage,
            Command = registration.Command,
            Arguments = registration.Arguments,
            WorkingDirectory = probe.Checkout,
            InheritEnvironmentVariables = false,
            EnvironmentVariables = environment,
            StandardErrorLines = line => Log("stderr: " + line)
        });
        await using var client = await McpClient.CreateAsync(new LaunchObserver(transport, () =>
        {
            probe.ProcessLaunch = "passed";
            launched();
        }), cancellationToken: timeout.Token);
        probe.Protocol = "initialized";
        initialized();
        Require(client.ServerInfo.Version == versions[Path.GetFileName(workspace.Executable)], "MCP server version differs from the packaged version.");
        var tools = await client.ListToolsAsync(cancellationToken: timeout.Token);
        Require(tools.Count == 2 && tools.All(tool => tool.ProtocolTool.OutputSchema is not null)
            && tools.Any(tool => tool.Name == "log_work") && tools.Any(tool => tool.Name == "query_work"),
            "Expected log_work and query_work with output schemas.");
        probe.Protocol = "initialize/tools-list passed (direct SDK)";
        toolsListed();
        var logged = await client.CallToolAsync("log_work", new Dictionary<string, object?>
        {
            ["entry"] = new
            {
                status = "in_progress",
                change = "worktree-startup",
                branch = "bugfix/DEP-610-worktrees",
                occurredAt = "2026-10-25T12:00:00Z",
                idempotencyKey = probe.Client + "-" + probe.Stage
            }
        }, cancellationToken: timeout.Token);
        Require(logged.IsError != true && logged.StructuredContent is not null, "Context logging failed.");
        var entry = logged.StructuredContent!.Value.GetProperty("entry");
        Log(entry.GetRawText());
        probe.RepositoryIdentity = entry.GetProperty("repository").GetString();
        Require(probe.RepositoryIdentity == identity, "Connection did not use the shared repository identity.");
        var tickets = entry.GetProperty("tickets").EnumerateArray().ToArray();
        Require(tickets.Length == 1 && tickets[0].GetProperty("provider").GetString() == "jira"
            && tickets[0].GetProperty("scope").GetString() == "worktree.example.invalid"
            && tickets[0].GetProperty("id").GetString() == "DEP-610", "Connection lost shared ticket context.");
        observationIds.Add(entry.GetProperty("id").GetString()!);
        var queried = await client.CallToolAsync("query_work", new Dictionary<string, object?>
        {
            ["period"] = new { from = "2026-10-25T00:00:00Z", to = "2026-10-26T00:00:00Z", timezone = "UTC", pageSize = 100 }
        }, cancellationToken: timeout.Token);
        Require(queried.IsError != true && queried.StructuredContent is not null, "Shared-history query failed.");
        var report = queried.StructuredContent!.Value;
        Require(!report.GetProperty("hasMore").GetBoolean() && observationIds.SetEquals(report.GetProperty("entries").EnumerateArray()
            .Select(observation => observation.GetProperty("id").GetString()!)), "Connections did not see the same complete fixture history.");
        probe.Context = "shared identity, qualified ticket and history passed";
        Log(JsonSerializer.Serialize(new
        {
            client.ServerInfo,
            tools = tools.Select(tool => tool.Name),
            probe.Context
        }));
    }

    private Registration ReadClaudeRegistration(string output)
    {
        // Claude's native output has no JSON mode. Match its displayed command AND full args
        // against only this fixture's private definitions; never reconstruct an assumed command.
        var config = JsonNode.Parse(File.ReadAllText(Path.Combine(Home, ".claude.json")))!;
        var definitions = config["projects"]!.AsObject().Select(pair => pair.Value?["mcpServers"]?["worklog"])
            .Where(server => server is not null).Select(server => new Registration(server!["command"]!.GetValue<string>(),
                server["args"]!.AsArray().Select(argument => argument!.GetValue<string>()).ToArray())).ToArray();
        var matches = definitions.Where(server => output.Split('\n').Any(line => line.Trim() == "Command: " + server.Command)
            && output.Split('\n').Any(line => line.Trim() == "Args: " + string.Join(' ', server.Arguments))).ToArray();
        Require(matches.Length == 1, "Claude output did not unambiguously identify a fixture registration.");
        return matches[0];
    }

    private async Task InitAsync(string checkout, string client, params string[] options)
    {
        await RunAsync(workspace.Executable, ["init", "--repository", checkout, "--data-dir", Data, "--clients", client, .. options], checkout);
        foreach (var selected in client == "both" ? new[] { "claude", "codex" } : [client])
        {
            Registration written;
            if (selected == "claude")
            {
                var server = JsonNode.Parse(File.ReadAllText(Path.Combine(Home, ".claude.json")))!
                    ["projects"]![GitRepository.GetRoot(checkout).Replace('\\', '/')]!["mcpServers"]!["worklog"]!;
                written = new(server["command"]!.GetValue<string>(), server["args"]!.AsArray().Select(value => value!.GetValue<string>()).ToArray());
            }
            else
            {
                var config = Toml.ToModel(File.ReadAllText(Path.Combine(checkout, ".codex", "config.toml")));
                var server = (TomlTable)((TomlTable)config["mcp_servers"])["worklog"];
                written = new((string)server["command"], ((TomlArray)server["args"]).Cast<string>().ToArray());
            }
            Require(SamePath(written.Command, workspace.Executable) && Argument(written, "--repository") is { } repository
                && SamePath(repository, checkout) && Argument(written, "--data-dir") is { } data && SamePath(data, Data),
                "Explicit init did not write the expected private " + selected + " registration for " + checkout);
        }
    }
    private async Task GitAsync(string checkout, params string[] arguments) => _ = await RunAsync("git", arguments, checkout);
    private async Task<SmokeProcessResult> RunAsync(string command, string[] arguments, string checkout)
    {
        var result = await processes.RunDetailedAsync(command, arguments, EnvironmentForFixture, checkout);
        setupLogs.Add(Relative(result.LogPath));
        Require(result.ExitCode == 0, $"Setup/prerequisite command {Path.GetFileName(command)} failed with exit {result.ExitCode}; see {result.LogPath}.");
        return result;
    }
    private void AssertFreshWorktree() => Require(!File.Exists(Path.Combine(Worktree, ".worklog", "integration.json"))
        && !File.Exists(Path.Combine(Worktree, ".codex", "config.toml")) && !File.Exists(Path.Combine(Worktree, "CLAUDE.local.md")),
        "Fresh-worktree probe must precede init or generated-file copying.");
    private string Relative(string path) => Path.GetRelativePath(workspace.Root, path);
    private static string? Argument(Registration registration, string flag)
    {
        var index = Array.IndexOf(registration.Arguments, flag);
        return index >= 0 && index + 1 < registration.Arguments.Length ? registration.Arguments[index + 1] : null;
    }
    private static bool SamePath(string first, string second) => string.Equals(Path.GetFullPath(first), Path.GetFullPath(second),
        OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal);
    private static void Require(bool condition, string message)
    {
        if (!condition)
            throw new InvalidOperationException(message);
    }
    private sealed record Registration(string Command, string[] Arguments);
    private sealed class LaunchObserver(IClientTransport inner, Action launched) : IClientTransport
    {
        public string Name => inner.Name;
        public async Task<ITransport> ConnectAsync(CancellationToken cancellationToken = default)
        {
            var session = await inner.ConnectAsync(cancellationToken);
            launched();
            return session;
        }
    }
    private sealed class Probe(string client, string stage, string checkout)
    {
        public string Client { get; } = client;
        public string Stage { get; } = stage;
        public string Checkout { get; } = checkout;
        public int? ClientExitCode
        {
            get; set;
        }
        public string Discovery { get; set; } = "not-run";
        public string NativeHealth { get; set; } = "not-run";
        public string ProcessLaunch { get; set; } = "not-run";
        public string Protocol { get; set; } = "not-run";
        public string Context { get; set; } = "not-run";
        public string? Command
        {
            get; set;
        }
        public string[]? Arguments
        {
            get; set;
        }
        public string? RepositoryArgument
        {
            get; set;
        }
        public string? DataDirectoryArgument
        {
            get; set;
        }
        public string? RepositoryIdentity
        {
            get; set;
        }
        public string? Failure
        {
            get; set;
        }
        public List<string> Logs { get; } = [];
    }
}
